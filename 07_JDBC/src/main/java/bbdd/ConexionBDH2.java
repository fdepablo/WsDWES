package bbdd;

import bbdd.interfaces.ConexionBD;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

/** Conexión H2 en archivo, sin instalar un servidor de bases de datos. */
public class ConexionBDH2 implements ConexionBD {
    // Ruta relativa al directorio de trabajo desde el que se ejecuta Tomcat.
    private static final String URL = "jdbc:h2:file:./datos/wsdwes_07_jdbc";
    private static final String USUARIO = "sa";
    private static final String PASSWORD = "";

    @Override
    public Connection abrir() throws SQLException {
        try {
            // Carga explícita del controlador que Maven incluye en WEB-INF/lib.
            Class.forName("org.h2.Driver");
        } catch (ClassNotFoundException e) {
            throw new SQLException("No se encuentra el controlador JDBC de H2.", e);
        }
        return DriverManager.getConnection(URL, USUARIO, PASSWORD);
    }

    /** Crea la tabla si falta, conservando los productos de ejecuciones anteriores. */
    @Override
    public void prepararBaseDatos() throws SQLException {
        try (Connection conexion = abrir(); Statement sentencia = conexion.createStatement()) {
            sentencia.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS productos (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nombre VARCHAR(80) NOT NULL,
                        precio DECIMAL(10, 2) NOT NULL
                    )
                    """);
        }
    }
}
